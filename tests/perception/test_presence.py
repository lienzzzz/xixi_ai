class SceneTests(unittest.TestCase):
    """The fixtures must behave as documented, otherwise every other test is meaningless."""

    def test_empty_scene_has_no_motion(self) -> None:
        signals = detect_script(still_track(6), detector="none")
        self.assertTrue(all(not signal.motion for signal in signals[1:]))
        self.assertEqual([round(s.motion_ratio, 5) for s in signals[1:]], [0.0] * 5)

