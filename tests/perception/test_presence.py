class DebounceTests(unittest.TestCase):
    """Hysteresis: the parameters and the reasons live in perception_edge/debounce.py."""

    def test_one_frame_of_evidence_does_not_flip_the_state(self) -> None:
        debouncer = PresenceDebouncer(
            DebounceConfig(present_confirm_frames=3, absent_confirm_frames=2, minimum_evidence_ms=100.0)
        )
        self.assertEqual(debouncer.state, ABSENT)
        first = debouncer.update(signal=True, motion_ratio=0.02, faces=0, timestamp_ms=0.0, frame_index=0)
        self.assertFalse(first.changed, "one frame of evidence must not flip the state")
        confirmations = []
        for index, timestamp in enumerate((100.0, 200.0, 300.0), start=1):
            decision = debouncer.update(signal=True, motion_ratio=0.02, faces=0, timestamp_ms=timestamp, frame_index=index)
            if decision.changed:
                confirmations.append((index, decision))
        self.assertEqual(len(confirmations), 1, "the state must flip exactly once")
        index, decision = confirmations[0]
        self.assertEqual(decision.state, PRESENT)
        self.assertEqual(decision.reason, "present_confirmed")
        self.assertEqual(index, 2, "3 consistent frames AND 100 ms of evidence")

    def test_evidence_shorter_than_the_minimum_is_noise(self) -> None:
        """A run shorter than `minimum_evidence_ms` never becomes "present"."""
        debouncer = PresenceDebouncer(
            DebounceConfig(present_confirm_frames=1, absent_confirm_frames=1, minimum_evidence_ms=1000.0)
        )
        debouncer.update(signal=True, motion_ratio=0.02, faces=0, timestamp_ms=0.0, frame_index=0)
        debouncer.update(signal=False, motion_ratio=0.0, faces=0, timestamp_ms=100.0, frame_index=1)
        self.assertEqual(debouncer.state, ABSENT)
        self.assertEqual(debouncer.counters.runs_rejected_as_too_short, 1)
        self.assertEqual(debouncer.counters.last_run_ms, 100.0)

    def test_evidence_longer_than_the_minimum_counts_normally(self) -> None:
        debouncer = PresenceDebouncer(
            DebounceConfig(present_confirm_frames=2, absent_confirm_frames=1, minimum_evidence_ms=1000.0)
        )
        decision = None
        for index, timestamp in enumerate((0.0, 33.0)):
            decision = debouncer.update(signal=True, motion_ratio=0.02, faces=0, timestamp_ms=timestamp, frame_index=index)
        self.assertEqual(decision.state, ABSENT)
        self.assertEqual(decision.reason, "burst_too_short")
        # A run that lasts past the minimum duration (and has enough frames) does confirm.
        confirmations = []
        for index, timestamp in enumerate((1000.0, 1033.0), start=2):
            decision = debouncer.update(signal=True, motion_ratio=0.02, faces=0, timestamp_ms=timestamp, frame_index=index)
            if decision.changed:
                confirmations.append(decision)
        self.assertEqual(len(confirmations), 1)
        self.assertEqual(confirmations[0].state, PRESENT)
        self.assertEqual(confirmations[0].reason, "present_confirmed")

    def test_single_glitch_frame_inside_the_window_is_ignored(self) -> None:
        if not face_backend_available("haar"):
            self.skipTest("Haar unavailable: OpenCV 5.0 removed cv2.CascadeClassifier")
        frames = still_track(20)
        frames[7] = (speckle_frame(), frames[7][1])
        captured = run_script(frames, detector="haar", **FIELD_THRESHOLDS)
        # Only the startup announcement; one bad frame must not produce a transition.
        self.assertEqual(captured.states, [ABSENT])
        self.assertGreaterEqual(captured.summary["counters"]["runs_rejected_as_too_short"], 1)

    def test_short_run_is_ignored_even_when_it_reaches_the_frame_threshold(self) -> None:
        # Four consecutive frames carry evidence: three walking positions plus the
        # transition back to the static scene. 4 frames >= 3, but the run lasts only
        # 100 ms, so it is still not a person.
        frames = still_track(10) + person_track(3, step=25, start_x=60) + still_track(10)
        captured = run_script(frames, detector="none", present_confirm_frames=3, absent_confirm_frames=3)
        self.assertEqual(captured.states, [ABSENT], "启动状态不是一次「变化」")
        self.assertEqual(captured.summary["counters"]["runs_rejected_as_too_short"], 1)
        self.assertEqual(captured.summary["counters"]["last_run_frames"], 4)

    def test_brief_occlusion_does_not_flip_the_state(self) -> None:
        """0.5 s with the lens covered must not produce absent-then-present again."""
        frames = person_track(80, step=14) + still_track(15) + person_track(80, step=14) + still_track(20)
        captured = run_script(frames, detector="none", **FIELD_THRESHOLDS)
        self.assertEqual(
            captured.states,
            [ABSENT, PRESENT],
            "brief coverage must not create an absence event",
        )

    def test_long_occlusion_reports_absence_exactly_once(self) -> None:
        """5 s of nothing *is* an absence - reported once, not repeatedly."""
        frames = person_track(80, step=14) + still_track(150) + person_track(80, step=14) + still_track(160)
        captured = run_script(frames, detector="none", **FIELD_THRESHOLDS)
        self.assertEqual(captured.states, [ABSENT, PRESENT, ABSENT, PRESENT, ABSENT])

    def test_release_grace_gates_absence_even_when_the_blank_window_is_reached(self) -> None:
        debouncer = PresenceDebouncer(
            DebounceConfig(
                present_confirm_frames=1,
                absent_confirm_frames=2,
                release_grace_ms=1000.0,
                minimum_evidence_ms=0.0,
            )
        )
        debouncer.update(signal=True, motion_ratio=0.02, faces=0, timestamp_ms=0.0, frame_index=0)
        self.assertEqual(debouncer.state, PRESENT)
        debouncer.update(signal=False, motion_ratio=0.0, faces=0, timestamp_ms=10.0, frame_index=1)
        decision = debouncer.update(signal=False, motion_ratio=0.0, faces=0, timestamp_ms=20.0, frame_index=2)
        self.assertFalse(decision.changed, "the grace period has not elapsed at 20 ms")
        self.assertEqual(decision.reason, "absent_pending")
        for index in range(3, 60):
            decision = debouncer.update(signal=False, motion_ratio=0.0, faces=0, timestamp_ms=index * 33.0, frame_index=index)
            if decision.changed:
                break
        self.assertTrue(decision.changed)
        self.assertEqual(decision.reason, "absent_confirmed")

    def test_attribution_is_recorded_on_entering_presence(self) -> None:
        """A stale confidence must not leak into the next state change (regression)."""
        debouncer = PresenceDebouncer(DebounceConfig(present_confirm_frames=1, minimum_evidence_ms=0.0))
        entering = debouncer.update(signal=True, motion_ratio=0.01, faces=0, timestamp_ms=0.0, frame_index=0)
        self.assertTrue(entering.changed)
        self.assertEqual(entering.confidence, 0.75, "motion-only arrival")

        face_debouncer = PresenceDebouncer(DebounceConfig(present_confirm_frames=1, minimum_evidence_ms=0.0))
        face_arrival = face_debouncer.update(signal=True, motion_ratio=0.01, faces=1, timestamp_ms=0.0, frame_index=0)
        self.assertEqual(face_arrival.confidence, 0.9, "a confirmed face is stronger evidence than motion")
        self.assertGreater(face_arrival.confidence, entering.confidence)


